/**
 * Fetches Rangpur Division boundary from OSM Overpass API and generates
 * a merged/continuous boundary data file.
 *
 * Key improvement: individual OSM ways are sorted and merged by matching
 * endpoints, producing continuous polylines instead of disconnected segments.
 *
 * Usage: node scripts/fetch-rangpur-boundary.mjs
 */

import { writeFileSync, readFileSync, mkdirSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OSM_RELATION_ID = 3921211; // Rangpur Division (Wikidata Q876023)

// ---- helpers ----

function cachePath() {
  return resolve(__dirname, "..", ".cache", "rangpur-boundary-raw.json");
}

function readCache() {
  try { return JSON.parse(readFileSync(cachePath(), "utf-8")); } catch { return null; }
}

function writeCache(data) {
  mkdirSync(resolve(__dirname, "..", ".cache"), { recursive: true });
  writeFileSync(cachePath(), JSON.stringify(data), "utf-8");
}

async function fetchBoundary() {
  const cached = readCache();
  if (cached) {
    console.log("Using cached data (delete .cache/rangpur-boundary-raw.json to re-fetch)");
    return cached;
  }
  const query = `[out:json];relation(${OSM_RELATION_ID});out geom;`;
  const res = await fetch("https://overpass-api.de/api/interpreter", {
    method: "POST",
    headers: {
      "Content-Type": "application/x-www-form-urlencoded; charset=utf-8",
      "User-Agent": "trinomul-blood-bank/1.0",
    },
    body: `data=${encodeURIComponent(query)}`,
  });
  if (!res.ok) throw new Error(`Overpass error: ${res.status}`);
  const data = await res.json();
  writeCache(data);
  return data;
}

function dist2(a, b) {
  const dlat = a[0] - b[0];
  const dlng = a[1] - b[1];
  return dlat * dlat + dlng * dlng;
}

// ---- Merge disconnected way segments into continuous chains ----

const EPSILON = 0.0002; // ~22 m — max gap to consider "connected"

function mergeRingsIntoChains(rings) {
  if (rings.length === 0) return [];
  const pool = rings.map((r) => [...r]); // deep copy
  const chains = [];

  while (pool.length > 0) {
    let chain = pool.shift();
    let grew = true;

    while (grew) {
      grew = false;
      for (let i = pool.length - 1; i >= 0; i--) {
        const ring = pool[i];

        // ring tail ≈ chain head
        if (dist2(ring[ring.length - 1], chain[0]) < EPSILON) {
          chain = [...ring.slice(0, -1), ...chain];
          pool.splice(i, 1);
          grew = true;
        }
        // ring head ≈ chain tail
        else if (dist2(ring[0], chain[chain.length - 1]) < EPSILON) {
          chain = [...chain, ...ring.slice(1)];
          pool.splice(i, 1);
          grew = true;
        }
        // ring head ≈ chain head (reverse ring)
        else if (dist2(ring[0], chain[0]) < EPSILON) {
          chain = [...ring.reverse().slice(0, -1), ...chain];
          pool.splice(i, 1);
          grew = true;
        }
        // ring tail ≈ chain tail (reverse ring)
        else if (dist2(ring[ring.length - 1], chain[chain.length - 1]) < EPSILON) {
          chain = [...chain, ...ring.reverse().slice(1)];
          pool.splice(i, 1);
          grew = true;
        }
      }
    }

    const isClosed = dist2(chain[0], chain[chain.length - 1]) < EPSILON;
    if (isClosed) {
      // Ensure closure: first == last
      chain[chain.length - 1] = [chain[0][0], chain[0][1]];
    }
    chains.push({ coords: chain, closed: isClosed });
  }

  return chains;
}

// ---- Code generation ----

function fmtCoords(coords, indent) {
  return coords.map(([lat, lng]) => `${indent}[${lat.toFixed(6)}, ${lng.toFixed(6)}]`).join(",\n");
}

function generateDataFile(allChains) {
  const polygons = allChains.filter((c) => c.closed);
  const polylines = allChains.filter((c) => !c.closed);

  polygons.sort((a, b) => b.coords.length - a.coords.length);
  polylines.sort((a, b) => b.coords.length - a.coords.length);

  let code = `/**
 * Rangpur Division boundary — OpenStreetMap relation ${OSM_RELATION_ID}.
 * Coordinates in Leaflet [lat, lng] format.
 * ${allChains.length} chains: ${polygons.length} closed polygons, ${polylines.length} open polylines.
 * Auto-generated by scripts/fetch-rangpur-boundary.mjs
 */\n\n`;

  if (polygons.length > 0) {
    code += `export const BOUNDARY_POLYGONS: [number, number][][] = [\n`;
    for (const p of polygons) {
      code += `  [\n${fmtCoords(p.coords, "    ")}\n  ],\n`;
    }
    code += `];\n\n`;
  } else {
    code += `export const BOUNDARY_POLYGONS: [number, number][][] = [];\n\n`;
  }

  if (polylines.length > 0) {
    code += `export const BOUNDARY_POLYLINES: [number, number][][] = [\n`;
    for (const p of polylines) {
      code += `  [\n${fmtCoords(p.coords, "    ")}\n  ],\n`;
    }
    code += `];\n\n`;
  } else {
    code += `export const BOUNDARY_POLYLINES: [number, number][][] = [];\n\n`;
  }

  code += `export const ALL_BOUNDARY_CHAINS: [number, number][][] = [
  ...BOUNDARY_POLYGONS,
  ...BOUNDARY_POLYLINES,
];\n`;

  return code;
}

function computeBounds(allChains) {
  let minLat = Infinity, maxLat = -Infinity, minLng = Infinity, maxLng = -Infinity;
  for (const c of allChains) {
    for (const [lat, lng] of c.coords) {
      if (lat < minLat) minLat = lat;
      if (lat > maxLat) maxLat = lat;
      if (lng < minLng) minLng = lng;
      if (lng > maxLng) maxLng = lng;
    }
  }
  return { sw: [minLat, minLng], ne: [maxLat, maxLng] };
}

// ---- Main ----

async function main() {
  console.log("Fetching Rangpur boundary from Overpass API...");
  const data = await fetchBoundary();
  console.log(`Got ${data.elements.length} relation(s)`);

  const outerRings = [];
  for (const el of data.elements) {
    if (el.type !== "relation") continue;
    for (const member of el.members) {
      if (member.type !== "way" || !member.geometry || member.role !== "outer") continue;
      outerRings.push(member.geometry.map((p) => [p.lat, p.lon]));
    }
  }

  console.log(`Raw outer ways: ${outerRings.length}`);

  const merged = mergeRingsIntoChains(outerRings);
  const totalVerts = merged.reduce((s, c) => s + c.coords.length, 0);
  const closed = merged.filter((c) => c.closed).length;
  const open = merged.filter((c) => !c.closed).length;

  console.log(`Merged: ${merged.length} chains (${totalVerts} vertices) — ${closed} closed, ${open} open`);

  const bounds = computeBounds(merged);
  console.log(`Bounds: [${bounds.sw[0].toFixed(5)}, ${bounds.sw[1].toFixed(5)}] → [${bounds.ne[0].toFixed(5)}, ${bounds.ne[1].toFixed(5)}]`);

  const outPath = resolve(__dirname, "..", "components", "map", "rangpur-boundary-data.ts");
  writeFileSync(outPath, generateDataFile(merged), "utf-8");
  console.log(`Written: ${outPath}`);
}

main().catch((err) => { console.error("Failed:", err); process.exit(1); });
